/*复习字符串以及常量的特性*/
#include <stdio.h>
// TODO  const char *str = "字符串常量";  双保险，如若修改在编译时就会报错
int main(int argc, char *argv[]) {
#if 1 /*普通字符串 - 可修改的字符数组*/
    char buf[] = "这是一个字符串"; 
    // 1. 这是一个可修改的字符数组（栈上分配）
    // 2. 总字节数 = 6个中文字符 * 3字节 + 1个'\0' = 19字节
    // 3. 不等于 char buf[8] = ...，因为中文字符不能用char单个存储
#elif 0 /*字符串常量 - 只读的指针*/
    char *buf = "这是一个字符串常量"; 
    // 1. buf是指向字符串字面量的指针
    // 2. 字符串字面量存储在只读数据段
    // 3. 尝试修改会导致段错误
#endif 

    char *str = buf;  // str指向buf，类型相同
    
    // const char *str = buf;  // 表示"str指向的内容是常量"
    // char * const str = buf; // 表示"str本身是常量（不能指向其他地方）"
    
    str[3] = 'A'; 
    // 危险操作：
    // 1. 如果buf是字符数组（当前情况）：语法正确，但会破坏UTF-8编码
    //    - 字节3是"是"字的第一个字节，修改它会破坏整个字符
    // 2. 如果buf指向字面量：语法正确，但运行时段错误
    // 3. 如果是const char *str：编译器会报错（语法错误）
    
    printf("%s\n", str);  // 可能输出乱码：因为UTF-8编码被破坏了
    return 0;
}